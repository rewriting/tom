// Package compiler — SyntacticPropagator.
//
// Java reference: stable/tom/engine/compiler/propagator/SyntacticPropagator.t
// (186 LOC).
//
// Fires on `MatchConstraint(p=RecordAppl(...), s=!SymbolOf, T=aType)`
// where the head symbol is a syntactic operator (not list/array/AC).
// The rewrite produces this conjunction (Java's
// SyntacticPatternMatching strategy):
//
//	MatchConstraint(freshSubject, g, aType)
//	  /\ OrConstraintDisjunction(
//	       per-name(N): AndConstraint(
//	         [IsSortConstraint(aType, freshSubject)   if aType != gType],
//	         MatchConstraint(RecordAppl(opts,[N],[],_), SymbolOf(freshSubject), aType),
//	         MatchConstraint(freshCastedSubject, freshSubject, aType),
//	         per slot(i): MatchConstraint(toVar(freshVar_i),
//	                                      Subterm(N, slotName_i, freshCastedSubject),
//	                                      slotType_i)
//	       )
//	     )
//	  /\ per slot(i): [IsSortConstraint(applType_i, freshVar_i) if applType_i != slotType_i],
//	                  MatchConstraint(appl_i, freshVar_i, applType_i)
//	  /\ <annotation-detach conjuncts>
//
// `freshSubject`, `freshCastedSubject`, `freshVar_i` are all
// generated by `getFreshVariable`. Annotation detach turns
// `name@pat << s` into `name << s ∧ pat << s` (Java
// ConstraintPropagator.performDetach).

package compiler

import (
	"tom/tomgo/stable/library/tomast"
)

// propagateSyntactic walks the constraint and applies the syntactic
// expansion top-down at every match-able node. Returns the rewritten
// constraint (same instance when nothing matched, like Java's
// stop-on-success).
func (env *compilerEnv) propagateSyntactic(c tomast.Constraint) tomast.Constraint {
	switch x := c.(type) {
	case *tomast.MatchConstraintConstraint:
		if rewritten, ok := env.tryExpandSyntactic(x); ok {
			return rewritten
		}
		return x
	case *tomast.AndConstraintConstraint:
		if ns, changed := mapConstraintSlots(x.Slots, env.propagateSyntactic); changed {
			return tomast.MakeAndConstraint(ns...)
		}
		return c
	case *tomast.OrConstraintConstraint:
		if ns, changed := mapConstraintSlots(x.Slots, env.propagateSyntactic); changed {
			return tomast.MakeOrConstraint(ns...)
		}
		return c
	}
	return c
}

// tryExpandSyntactic does the actual rewrite on one MatchConstraint.
// Returns (newConstraint, true) when the syntactic rule fires;
// returns (input, false) otherwise.
func (env *compilerEnv) tryExpandSyntactic(m *tomast.MatchConstraintConstraint) (tomast.Constraint, bool) {
	pat, ok := m.Pattern.(*tomast.RecordApplTomTerm)
	if !ok {
		return m, false
	}
	// Bail when the subject is already a SymbolOf — that's a guard,
	// not a fresh subject.
	if _, isSymbolOf := m.Subject.(*tomast.SymbolOfBQTerm); isSymbolOf {
		return m, false
	}

	nameList, ok := pat.NameList.(*tomast.ConcTomNameTomNameList)
	if !ok || len(nameList.Slots) == 0 {
		return m, false
	}
	firstName, ok := nameList.Slots[0].(*tomast.NameTomName)
	if !ok {
		return m, false
	}
	tomName := firstName.String_

	// Only syntactic ops trigger this expansion. List/array/AC ops
	// have their own propagators.
	if !env.isSyntacticOperator(tomName) {
		return m, false
	}

	aType := m.AstType
	g := m.Subject
	gType := env.termTypeOfBQTerm(g)
	freshSubject := env.getFreshVariable(gType)

	// Build the "lastPart" conjunction: per-slot constraints linking
	// the fresh var to the original appl. Collect fresh vars by
	// position so the disjunction can refer to them.
	slots, _ := pat.Slots.(*tomast.ConcSlotSlotList)
	freshVars := []tomast.BQTerm{}
	lastPart := []tomast.Constraint{}
	if slots != nil {
		for _, s := range slots.Slots {
			pair, ok := s.(*tomast.PairSlotApplSlot)
			if !ok {
				continue
			}
			applType := env.termTypeOfTomTerm(pair.Appl)
			slotType := env.slotTypeFor(tomName, nameString(pair.SlotName))
			freshVar := env.getFreshVariable(slotType)
			freshVars = append(freshVars, freshVar)
			if applType != slotType && applType != nil {
				lastPart = append(lastPart,
					tomast.MakeIsSortConstraint(applType, freshVar))
			}
			lastPart = append(lastPart,
				tomast.MakeMatchConstraint(pair.Appl, freshVar, applType))
		}
	}

	// Build the per-name disjunction. For each name in NameList,
	// emit the AndConstraint of (IsSort?, MatchConstraint(RecordAppl([name]), SymbolOf(freshSubject)),
	// MatchConstraint(freshCasted, freshSubject), per-slot Subterm match).
	disjuncts := []tomast.Constraint{}
	for _, n := range nameList.Slots {
		andForName := []tomast.Constraint{}
		if !sameTomType(aType, gType) {
			andForName = append(andForName,
				tomast.MakeIsSortConstraint(aType, freshSubject))
		}
		// IsFsym-equivalent: MatchConstraint(RecordAppl(opts, [N], [], _), SymbolOf(freshSubject), aType).
		symbolOfFresh := tomast.MakeSymbolOf(freshSubject)
		applForName := tomast.MakeRecordAppl(
			pat.Options,
			tomast.MakeConcTomName(n),
			tomast.MakeConcSlot(),
			tomast.MakeConcConstraint(),
		)
		andForName = append(andForName,
			tomast.MakeMatchConstraint(applForName, symbolOfFresh, aType))

		freshCastedSubject := env.getFreshVariable(aType)
		freshCastedVar := convertBQVarToVar(freshCastedSubject)
		andForName = append(andForName,
			tomast.MakeMatchConstraint(freshCastedVar, freshSubject, aType))

		// Per-slot subterm matches.
		if slots != nil {
			i := 0
			for _, s := range slots.Slots {
				pair, ok := s.(*tomast.PairSlotApplSlot)
				if !ok {
					continue
				}
				if i >= len(freshVars) {
					break
				}
				slotType := env.slotTypeFor(nameString(n), nameString(pair.SlotName))
				freshVarT := convertBQVarToVar(freshVars[i])
				andForName = append(andForName,
					tomast.MakeMatchConstraint(
						freshVarT,
						tomast.MakeSubtermBQTerm(n, pair.SlotName, freshCastedSubject),
						slotType,
					))
				i++
			}
		}
		disjuncts = append(disjuncts, tomast.MakeAndConstraint(andForName...))
	}

	conjunction := []tomast.Constraint{
		tomast.MakeMatchConstraint(convertBQVarToVar(freshSubject), g, aType),
		tomast.MakeOrConstraintDisjunction(disjuncts...),
	}
	conjunction = append(conjunction, lastPart...)
	conjunction = append(conjunction, env.performDetach(m)...)
	return tomast.MakeAndConstraint(conjunction...), true
}

// performDetach turns annotation constraints carried on a pattern
// (`name@<sub-pat>` → AliasTo) into top-level MatchConstraints. Java
// ConstraintPropagator.performDetach (lines 113-138).
//
// Returns the additional constraints; the caller appends them to
// the conjunction.
func (env *compilerEnv) performDetach(m *tomast.MatchConstraintConstraint) []tomast.Constraint {
	g := m.Subject
	aType := m.AstType
	var conlist tomast.ConstraintList
	switch p := m.Pattern.(type) {
	case *tomast.RecordApplTomTerm:
		conlist = p.Constraints
	case *tomast.VariableTomTerm:
		conlist = p.Constraints
	case *tomast.VariableStarTomTerm:
		// Java's full version introduces a fresh VariableStar to
		// avoid re-evaluating the subject (which may be a loop-
		// driving VariableHeadArray). For the minimal port we
		// duplicate the subject reference — correct for
		// GetSliceArray subjects (single fetch), potentially
		// duplicating work for VariableHeadArray subjects.
		conlist = p.Constraints
	default:
		return nil
	}
	conc, ok := conlist.(*tomast.ConcConstraintConstraintList)
	if !ok {
		return nil
	}
	out := []tomast.Constraint{}
	for _, c := range conc.Slots {
		alias, ok := c.(*tomast.AliasToConstraint)
		if !ok {
			continue
		}
		out = append(out, tomast.MakeMatchConstraint(alias.Var, g, aType))
	}
	return out
}

// sameTomType returns true when two TomTypes refer to the same sort.
// Java compares by reference (TomType is hash-consed), which works
// here too since we use the same Factory.
func sameTomType(a, b tomast.TomType) bool {
	if a == nil || b == nil {
		return a == b
	}
	// Both are *TypeTomType in practice — compare interface identity
	// (works because Factory.Build returns canonical instances).
	return a == b
}
