package sl

// AbstractStrategyBasic is the helper base for user-defined rewrite
// strategies — what Java's generated `%strategy ... visit T { ... }`
// extends. The contract:
//
//   - The struct embeds an [AbstractStrategyBasic].
//   - The user supplies VisitLight that dispatches on the subject's
//     concrete type. For types it knows how to rewrite, it returns the
//     new subject. For types it doesn't handle, it delegates to
//     `Any()` (the default strategy, typically [Identity]).
//
// Java reference:
//
//	public abstract class AbstractStrategyBasic extends AbstractStrategy {
//	  protected Strategy any;
//	  public AbstractStrategyBasic(Strategy v) { this.any = v; }
//	  ...
//	}
//
// Go embeds this struct and provides its own VisitLight. The single
// "any" slot is exposed as the first child (ChildAt(0)) so that
// strategy-tree traversers like [Mu] can still walk through it.
type AbstractStrategyBasic struct {
	abstractCombinator
}

// NewAbstractStrategyBasic constructs the helper with the supplied
// default strategy. Pass [NewIdentity] for the standard "no rewrite
// here, just keep walking" behaviour generated by the Tom compiler.
func NewAbstractStrategyBasic(any Strategy) *AbstractStrategyBasic {
	a := &AbstractStrategyBasic{}
	a.initSubterm(any)
	return a
}

// Any returns the default strategy that user code should fall back to
// when its rewrite rule doesn't apply. Equivalent to Java's protected
// `any` field.
func (a *AbstractStrategyBasic) Any() Strategy { return a.args[0] }

// VisitLight on the bare helper is just `any` — user code is expected
// to override by providing its own VisitLight on the embedding struct.
// This stub exists so a stand-alone AbstractStrategyBasic still
// satisfies [Strategy] (handy for tests and for default-of-default
// fallbacks).
func (a *AbstractStrategyBasic) VisitLight(subject any, intro Introspector) (any, error) {
	return a.args[0].VisitLight(subject, intro)
}

// embedderMsg is the panic message of the bare helper's environment-based methods.
const embedderMsg = "sl: embedding strategy must define VisitEnv/Visit/VisitWith: Go has no virtual dispatch"

// VisitEnv, Visit and VisitWith of the bare helper panic: Go has no
// virtual dispatch, so the helper cannot call the VisitLight of the
// strategy embedding it. An embedding strategy that is visited through
// the environment-based API must define them as
//
//	func (r *R) VisitEnv(i Introspector) int { return VisitBasic(r, i) }
//	func (r *R) Visit(s any, i Introspector) (any, error) { return VisitStrategy(r, s, i) }
//	func (r *R) VisitWith(e *Environment, i Introspector) (any, error) { return VisitStrategyWith(r, e, i) }
func (a *AbstractStrategyBasic) VisitEnv(Introspector) int { panic(embedderMsg) }

func (a *AbstractStrategyBasic) Visit(any, Introspector) (any, error) { panic(embedderMsg) }

func (a *AbstractStrategyBasic) VisitWith(*Environment, Introspector) (any, error) {
	panic(embedderMsg)
}
